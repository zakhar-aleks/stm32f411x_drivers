void I2C_GPIO_Init(void)
{
	GPIO_Handle I2CPins;

	I2CPins.pGPIOx = GPIOB;
	I2CPins.GPIO_PinConfig.GPIO_PIN_MODE = GPIO_MODE_ALT_FUNC;
	I2CPins.GPIO_PinConfig.GPIO_PIN_ALT_FUNC_MODE = GPIO_AF_NO_4;
	I2CPins.GPIO_PinConfig.GPIO_PIN_OUTPUT_TYPE = GPIO_OPEN_DRAIN;
	I2CPins.GPIO_PinConfig.GPIO_PIN_PUPD_MODE = GPIO_PUPD_PU;
	I2CPins.GPIO_PinConfig.GPIO_PIN_SPEED = GPIO_SPEED_HIGH;

	I2CPins.GPIO_PinConfig.GPIO_PIN_NUMBER = GPIO_PIN_NO_8;
	GPIO_Init(&I2CPins);

	I2CPins.GPIO_PinConfig.GPIO_PIN_NUMBER = GPIO_PIN_NO_9;
	GPIO_Init(&I2CPins);
}

void I2C1_Init(void)
{
	I2C_PeriClockControl(I2C1, ENABLE);

	I2C1Handle.pI2Cx = I2C1;
	I2C1Handle.I2C_Config.SCLSpeed = I2C_SCL_SPEED_SM;
	I2C1Handle.I2C_Config.SCLSpeedMode = I2C_SM_MODE;
	I2C1Handle.I2C_Config.DeviceAddress = 0x3C;
	I2C1Handle.I2C_Config.ACKControl = I2C_ACK_ENABLE;
	I2C1Handle.I2C_Config.FMDutyCycle = I2C_FM_DUTY_MODE_2;

	I2C_Init(&I2C1Handle);
}

int main(void)
{
	I2C_GPIO_Init();
	I2C1_Init();
	I2C_Peripheral_Control(I2C1, ENABLE);

	for (uint32_t i = 0; i < 500000; i++)
		;

	uint8_t init_sequence[] = { 0x00, 0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0x7F,
			0x22, 0x00, 0x07, 0xB0, 0xC8, 0x00, 0x10, 0x40, 0x81,
			0xFF, 0xA1, 0xA6, 0xA8, 0x3F, 0xA4, 0xD3, 0x00, 0xD5,
			0xF0, 0xD9, 0x22, 0xDA, 0x12, 0xDB, 0x20, 0x8D, 0x14,
			0xAF };

	I2C_MasterSendData(&I2C1Handle, init_sequence, sizeof(init_sequence),
			0x3C, I2C_DISABLE_RS);

	for (uint8_t page = 0; page < 8; page++) {

		uint8_t page_cmds[] = { 0x00, (uint8_t) (0xB0 + page), 0x00,
				0x10 };
		I2C_MasterSendData(&I2C1Handle, page_cmds, sizeof(page_cmds),
				0x3C, I2C_DISABLE_RS);

		uint8_t page_data[129];
		page_data[0] = 0x40;

		for (uint16_t col = 0; col < 128; col++) {
			page_data[col + 1] = img[(page * 128) + col];
		}

		I2C_MasterSendData(&I2C1Handle, page_data, 129, 0x3C,
				I2C_DISABLE_RS);
	}

	while (1) {
	}

	return 0;
}
